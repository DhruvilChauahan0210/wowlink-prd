/** A wording guide in a language: its own words from the translation, its wordings (already in every language) as they are. */
export function wordingIn(guide: WordingGuide, lang: Lang): WordingGuide {
  if (lang === "en") return guide;
  const text = WORDING_TEXT[lang][guide.slug];
  if (!text) return guide;
  const titles = WORDING_TITLES[lang];
  return { ...guide, ...text, wordings: guide.wordings.map((wording) => ({ ...wording, title: titles[wording.title] ?? wording.title })) };
}
