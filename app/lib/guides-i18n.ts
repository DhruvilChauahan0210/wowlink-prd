/** A guide in a language: its words from the translation, everything else (the occasion, the date) from the guide. */
export function guideIn(guide: Guide, lang: Lang): Guide {
  if (lang === "en") return guide;
  const text = GUIDE_TEXT[lang][guide.slug];
  return text ? { ...guide, ...text } : guide;
}
