/** A host-facing message in the host's language (validation and server messages arrive in English). */
export function hostMessage(message: string, lang: Lang) {
  if (lang === "en" || !message) return message;
  for (const [pattern, replacement] of ERRORS_GU) {
    const match = message.match(pattern);
    if (match) return typeof replacement === "string" ? replacement : replacement(...match.slice(1));
  }
  return message;
}
